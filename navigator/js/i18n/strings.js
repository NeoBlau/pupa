let current = 'ru';

export function setLang(lang) { current = LANGS.includes(lang) ? lang : 'ru'; }
export function getLang() { return current; }

export function detectLang() {
  const stored = localStorage.getItem('nav.lang');
  if (LANGS.includes(stored)) return stored;
  return (navigator.language || 'ru').toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

/** t('route.via', {name: 'M-11'}) — missing keys fall back to the key itself. */
export function t(key, vars) {
  let str = DICT[current]?.[key] ?? DICT.ru[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
  return str;
}

/** Russian plural rules: plural(5, ['камера','камеры','камер']). */
export function plural(n, forms) {
  if (current !== 'ru') return forms[n === 1 ? 0 : 1] ?? forms[1];
  const mod10 = n % 10, mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return forms[1];
  return forms[2];
}
